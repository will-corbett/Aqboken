/**
 * Aqböken's word lists: vocabulary themes, and the words the grammar drills use. Meanings are our own.
 * `npm run data:check` checks every word against Wiktionary (and each noun's and verb's forms against its tables).
 *
 * Verbs are listed by dictionary form (the -у form: бару) with their stem (бар). Options on nouns (harmony,
 * noVoicing, possStem) are for words the general rules don't fit; each must be confirmed by the check or a source.
 */
import type { Harmony } from '../shared/kazakh.ts';

export type Pos = 'n' | 'v' | 'adj' | 'adv' | 'pron' | 'num' | 'phr' | 'post' | 'conj';
export type Level = 'A1' | 'A2' | 'B1';

export interface Word {
  kk: string;
  en: string;
  pos: Pos;
  theme: string;
  /** Verbs: the stem the endings go on. */
  stem?: string;
  harmony?: Harmony;
  noVoicing?: boolean;
  possStem?: string;
  /** Verbs of going and coming: “right now” uses the -а/-е form (бара жатыр), not -ып. */
  motion?: boolean;
  /** Not used in the possessive and case drills (a mass noun, a name of a day, a word that reads oddly there). */
  noDrill?: boolean;
  /** Also listed in an earlier theme: shown here, but drilled and checked once. */
  dup?: boolean;
  /** A compound already ending in the 3rd-person possessive (отбасы = от + басы): its cases are отбасына, отбасын … */
  possessed?: boolean;
}

export interface Theme {
  id: string;
  title: string;
  kkTitle: string;
  level: Level;
  blurb: string;
  words: Word[];
}

type Extra = Partial<Omit<Word, 'kk' | 'en' | 'pos' | 'theme'>>;
let current = '';
const n = (kk: string, en: string, x: Extra = {}): Word => ({ kk, en, pos: 'n', theme: current, ...x });
const v = (kk: string, stem: string, en: string, x: Extra = {}): Word => ({ kk, en, pos: 'v', stem, theme: current, ...x });
const a = (kk: string, en: string): Word => ({ kk, en, pos: 'adj', theme: current });
const w = (pos: Pos, kk: string, en: string): Word => ({ kk, en, pos, theme: current });

function theme(id: string, title: string, kkTitle: string, level: Level, blurb: string, words: () => Word[]): Theme {
  current = id;
  return { id, title, kkTitle, level, blurb, words: words() };
}

